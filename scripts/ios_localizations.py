"""Generate native resources from the same five RoomCall translation catalogs."""

from __future__ import annotations

import json
import sys
from functools import partial
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    check = "--check" in sys.argv
    quote = partial(json.dumps, ensure_ascii=False)
    for locale in ("en", "es", "de", "fr", "nl"):
        catalog = json.loads(
            (ROOT / f"custom_components/roomcall/translations/{locale}.json").read_text()
        )["selector"]["communication"]["options"]
        values = {key: value for key, value in catalog.items() if key.startswith("ios_")}
        outputs = {
            "Localizable.strings": values,
            "InfoPlist.strings": {
                "NSMicrophoneUsageDescription": values["ios_microphone_permission"],
                "NSLocalNetworkUsageDescription": values["ios_local_network_permission"],
                "NSCameraUsageDescription": values["ios_camera_permission"],
            },
            "AppShortcuts.strings": {
                "Open ${applicationName}": values["ios_phrase_open"],
                "Announce with ${applicationName}": values["ios_phrase_announce"],
                "Mark a ${applicationName} task done": values["ios_phrase_done"],
                "Set ${applicationName} Do Not Disturb": values["ios_phrase_dnd"],
            },
        }
        for filename, strings in outputs.items():
            output = ROOT / f"ios/RoomCall/Resources/{locale}.lproj/{filename}"
            content = "// Generated by scripts/ios_localizations.py; edit the HA catalogs.\n"
            content += (
                "\n".join(
                    f"{quote(key)} = {quote(value)};" for key, value in sorted(strings.items())
                )
                + "\n"
            )
            if check:
                if not output.exists() or output.read_text() != content:
                    raise SystemExit(f"Stale native translations: {output.relative_to(ROOT)}")
            else:
                output.parent.mkdir(parents=True, exist_ok=True)
                output.write_text(content)


if __name__ == "__main__":
    main()
